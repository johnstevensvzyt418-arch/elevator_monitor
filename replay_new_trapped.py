def send(raw, tstr):
    params = urllib.parse.urlencode({
        "data": raw,
        "time": tstr,
        "elevatorID": DEVICE,
    }).encode()
    try:
        req = urllib.request.Request(BACKEND, data=params, method="POST")
        with urllib.request.urlopen(req, timeout=5) as resp:
            return resp.read().decode()
    except Exception as e:
        return "ERR: %s" % e


def main():
    print("=== 新困人数据报回放开始, 设备 %s ===" % DEVICE)
    for i, (raw, delay) in enumerate(frames, 1):
        if delay > 0:
            time.sleep(delay)
        tstr = raw[1:20]
        ret = send(raw, tstr)
        print("[%02d] %s  ret=%s" % (i, tstr, ret))
        time.sleep(0.3)
        # 内招复位后（第16帧）停留，观察真实困人（门未开）
        if i == 16:
            print("[!!] 内招复位,门未开 → 观察困人是否保持 (停留 15s)")
            time.sleep(15)
    print("=== 回放完成 ===")


if __name__ == "__main__":
    main()
