def send(raw, tstr):
    params = urllib.parse.urlencode({
        "data": raw,
        "time": tstr,
        "elevatorID": DEVICE,
    }).encode()
    try:
        req = urllib.request.Request(BACKEND, data=params, method="POST")
        with urllib.request.urlopen(req, timeout=5) as resp:
            body = resp.read().decode()
            return body
    except Exception as e:
        return "ERR: %s" % e


def main():
    print("=== 真实困人报文回放开始, 设备 %s ===" % DEVICE)
    for i, (raw, delay) in enumerate(frames, 1):
        if delay > 0:
            time.sleep(delay)
        tstr = raw[1:20]
        ret = send(raw, tstr)
        print("[%02d] %s  ret=%s" % (i, tstr, ret))
        time.sleep(0.3)  # 帧间小间隔，保证事件顺序
        # 困人触发后（第9帧内招复位、门仍关）停留更长时间，便于前端观察困人灯
        if i == 9:
            print("[!!] 困人告警保持中... 观察前端困人灯 (停留 30s)")
            time.sleep(30)
        elif i in (6, 7, 8):
            time.sleep(2.0)
    print("=== 回放完成 ===")


if __name__ == "__main__":
    main()
